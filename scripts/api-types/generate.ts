import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const input = Bun.argv[2];
if (!input) throw new Error("Usage: bun run generate:api <openapi.json>");
const source = await Bun.file(input).json();
const ast = await openapiTS(pathToFileURL(resolve(input)));
await Bun.write(
  "src/api-schema.ts",
  `// Generated by scripts/api-types/generate.ts. Do not edit.\n${astToString(ast, { formatOptions: { removeComments: true } })}`,
);
const values = Object.entries({ CHAINS: "Chain", WEBHOOK_EVENT_TYPES: "WebhookEvent" }).map(
  ([name, schema]) => {
    const entries: unknown = source.components?.schemas?.[schema]?.enum;
    if (!Array.isArray(entries) || !entries.length || !entries.every((value) => typeof value === "string")) {
      throw new Error(`Missing string enum: ${schema}`);
    }
    return `export const ${name} = ${JSON.stringify(entries)} as const;`;
  },
);
await Bun.write(
  "src/api-values.ts",
  `// Generated by scripts/api-types/generate.ts. Do not edit.\n${values.join("\n")}\n`,
);

const formatted = Bun.spawn(
  ["bun", "x", "biome", "format", "--write", "src/api-schema.ts", "src/api-values.ts"],
  { stdout: "inherit", stderr: "inherit" },
);
if ((await formatted.exited) !== 0) throw new Error("Generated type formatting failed");
